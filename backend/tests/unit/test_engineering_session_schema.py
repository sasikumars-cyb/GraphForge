"""Schema-shape tests for RFC-001's migration (`42c15cf49ec2`).

Not a destructive alembic upgrade/downgrade run against the shared test
database (see RFC-001.md's Known Limitations for why that's deliberately
left as a manually-verified, not automated-in-CI, step for this pass).
Instead, this asserts the ORM models — which the migration was
autogenerated from and hand-verified to match exactly — define the table
shape Architecture v2.1 requires: the right tables, the joined-table
inheritance chain, and the N-ary Contradiction join table.
"""

from __future__ import annotations

from app.database.base import Base
from app.models.belief import Belief, Hypothesis
from app.models.contradiction import Contradiction, ContradictionParty
from app.models.decision import Decision, Recommendation
from app.models.engineering_artifact import EngineeringArtifact
from app.models.engineering_session import SESSION_STATUSES, TimelineEntry
from app.models.evidence import Evidence
from app.models.participant import AGENT_ROLES, Participant

_EXPECTED_TABLES = {
    "participants",
    "engineering_sessions",
    "engineering_artifacts",
    "timeline_entries",
    "beliefs",
    "evidence",
    "hypotheses",
    "recommendations",
    "decisions",
    "contradictions",
    "contradiction_parties",
}


def test_every_rfc_001_table_is_registered_on_base_metadata():
    assert _EXPECTED_TABLES.issubset(set(Base.metadata.tables))


def test_joined_table_inheritance_subtypes_share_the_artifact_base_primary_key():
    for model in (Belief, Hypothesis, Evidence, Decision, Recommendation, Contradiction):
        pk_columns = {c.name for c in model.__table__.primary_key.columns}
        assert pk_columns == {"id"}, model
        fk_targets = {
            fk.target_fullname for col in model.__table__.columns for fk in col.foreign_keys
        }
        assert "engineering_artifacts.id" in fk_targets, model


def test_contradiction_party_references_the_shared_artifact_base_table():
    """The real, enforced expression of "N-ary, mixed-type disputes" —
    `artifact_id` targets `engineering_artifacts`, not any one concrete
    subtype (Architecture v2.1 §2.2, Δ v2.1)."""
    fk_targets = {
        fk.target_fullname
        for col in ContradictionParty.__table__.columns
        for fk in col.foreign_keys
    }
    assert "engineering_artifacts.id" in fk_targets
    assert "contradictions.id" in fk_targets


