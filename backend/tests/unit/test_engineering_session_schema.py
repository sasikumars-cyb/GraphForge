def test_engineering_session_owns_timeline_and_artifacts_by_composition():
    """Cascade delete — Architecture v2.1 §2.2: Session owns its Timeline
    and every Engineering Artifact (composition, not reference)."""
    session_fks = {
        (col.table.name, fk.column.table.name, fk.ondelete)
        for col in TimelineEntry.__table__.columns
        for fk in col.foreign_keys
        if fk.column.table.name == "engineering_sessions"
    }
    assert ("timeline_entries", "engineering_sessions", "CASCADE") in session_fks

    artifact_session_fks = {
        (col.table.name, fk.column.table.name, fk.ondelete)
        for col in EngineeringArtifact.__table__.columns
        for fk in col.foreign_keys
        if fk.column.table.name == "engineering_sessions"
    }
    assert ("engineering_artifacts", "engineering_sessions", "CASCADE") in artifact_session_fks
