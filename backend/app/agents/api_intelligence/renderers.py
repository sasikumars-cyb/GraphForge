def render_openapi_yaml(result: ApiIntelligenceResult) -> str:
    """Best-effort OpenAPI 3.0 document. "Best-effort" because Markdown
    prose doesn't reliably carry a machine JSON Schema for request/response
    bodies — those are attached as free-text `description` (with the
    original example under `x-example`) rather than fabricated as a typed
    schema the documentation never actually specified."""
    paths: dict[str, dict[str, object]] = {}
    for endpoint in result.endpoints:
        path_item = paths.setdefault(endpoint.path, {})
        operation: dict[str, object] = {
            "summary": endpoint.description or f"{endpoint.method} {endpoint.path}",
            "parameters": [
                {
                    "name": p.name,
                    "in": p.location if p.location != "body" else "query",
                    "required": p.required,
                    "description": p.description,
                    "schema": {"type": p.type or "string"},
                }
                for p in endpoint.parameters
                if p.location != "body"
            ],
            "responses": {
                code: {"description": f"HTTP {code}"} for code in (endpoint.status_codes or ["200"])
            },
        }
        if endpoint.version:
            operation["x-version"] = endpoint.version
        if endpoint.owner:
            operation["x-owner"] = endpoint.owner
        if endpoint.request_example:
            operation["requestBody"] = {
                "description": "See x-example-request for the documented sample payload.",
                "content": {"application/json": {"x-example-request": endpoint.request_example}},
            }
        if endpoint.response_example:
            operation["responses"].setdefault("200", {})["x-example-response"] = (  # type: ignore[index]
                endpoint.response_example
            )
        if endpoint.authentication_required:
            operation["security"] = [{"bearerAuth": []}]
        path_item[endpoint.method.lower()] = operation

    document: dict[str, object] = {
        "openapi": "3.0.3",
        "info": {
            "title": f"{result.repository_full_name} API",
            "description": result.executive_summary
            or "Generated by the API Intelligence Agent from Markdown documentation.",
            "version": (
                result.endpoints[0].version
                if result.endpoints and result.endpoints[0].version
                else "1.0.0"
            ),
        },
        "servers": [{"url": url} for url in result.base_urls]
        or [{"url": "https://api.example.com"}],
        "paths": paths,
    }
    if any(e.authentication_required for e in result.endpoints):
        document["components"] = {
            "securitySchemes": {"bearerAuth": {"type": "http", "scheme": "bearer"}}
        }

    return yaml.safe_dump(document, sort_keys=False, default_flow_style=False)


