def render_postman_collection(result: ApiIntelligenceResult) -> dict[str, object]:
    items = []
    for endpoint in result.endpoints:
        raw_url = (
            f"{endpoint.base_url.rstrip('/')}{endpoint.path}"
            if endpoint.base_url
            else endpoint.path
        )
        parsed = urlparse(raw_url)
        headers = [{"key": "Content-Type", "value": "application/json"}]
        if endpoint.authentication_required:
            headers.append({"key": "Authorization", "value": "Bearer {{token}}"})

        request: dict[str, object] = {
            "method": endpoint.method,
            "header": headers,
            "url": {
                "raw": raw_url,
                "host": [parsed.netloc] if parsed.netloc else [raw_url],
                "path": [p for p in parsed.path.split("/") if p] or [endpoint.path],
            },
            "description": endpoint.description,
        }
        if endpoint.method in ("POST", "PUT", "PATCH") and endpoint.request_example:
            request["body"] = {"mode": "raw", "raw": endpoint.request_example}

        items.append(
            {
                "name": f"{endpoint.method} {endpoint.path}",
                "request": request,
                "response": (
                    [
                        {
                            "name": "Example response",
                            "originalRequest": request,
                            "body": endpoint.response_example,
                        }
                    ]
                    if endpoint.response_example
                    else []
                ),
            }
        )

    return {
        "info": {
            "name": f"{result.repository_full_name} API",
            "description": result.executive_summary,
            "schema": "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
        },
        "item": items,
    }


