def render_markdown_summary(result: ApiIntelligenceResult) -> str:
    lines: list[str] = [f"# API Intelligence Report — {result.repository_full_name}", ""]
    if result.executive_summary:
        lines += [result.executive_summary, ""]

    lines += ["## Scores", ""]
    s = result.scores
    lines += [
        f"- **Overall Readiness:** {s.overall_readiness_score}/100",
        f"- Documentation Completeness: {s.documentation_completeness}/100",
        f"- Security: {s.security_score}/100",
        f"- API Quality: {s.api_quality_score}/100",
        f"- Readability: {s.readability_score}/100",
        f"- Consistency: {s.consistency_score}/100",
        "",
    ]

    lines += ["## Endpoints", ""]
    if not result.endpoints:
        lines += ["_No endpoints were extracted from the provided documentation._", ""]
    for e in result.endpoints:
        lines += [
            f"### {e.method} {e.path}",
            "",
            e.description or "_No description documented._",
            "",
            f"- Auth required: {'yes' if e.authentication_required else 'no'}",
            f"- Owner: {e.owner or 'undocumented'}",
            f"- Version: {e.version or 'undocumented'}",
            f"- Status codes: {', '.join(e.status_codes) or 'undocumented'}",
            f"- Source: `{e.source_file}`",
            "",
        ]
        if e.parameters:
            lines.append("| Parameter | In | Type | Required | Description |")
            lines.append("|---|---|---|---|---|")
            for p in e.parameters:
                lines.append(
                    f"| {p.name} | {p.location} | {p.type} | {p.required} | {p.description} |"
                )
            lines.append("")
        if e.request_example:
            lines += ["**Request example**", "```json", e.request_example, "```", ""]
        if e.response_example:
            lines += ["**Response example**", "```json", e.response_example, "```", ""]
        lines += ["**cURL**", "```bash", curl_for_endpoint(e), "```", ""]

    for title, value in (
        ("Authentication", result.authentication),
        ("Authorization", result.authorization),
        ("Rate Limits", result.rate_limits),
        ("Pagination", result.pagination),
        ("Versioning", result.versioning),
    ):
        if value:
            lines += [f"## {title}", "", value, ""]

    if result.security_findings:
        lines += ["## Security Findings", ""]
        for f in sorted(result.security_findings, key=lambda f: _SEVERITY_ORDER[f.severity]):
            lines += [
                f"### [{f.severity.upper()}] {f.title}",
                "",
                f"**Category:** {f.category}",
                "",
                f.description,
                "",
                f"**Why it matters:** {f.why_it_matters}",
                "",
                f"**Recommendation:** {f.recommendation}",
                "",
            ]

    if result.missing_information:
        lines += ["## Missing Information", ""]
        lines += [f"- {item}" for item in result.missing_information]
        lines += [""]

    if result.assumptions or result.todos or result.open_questions:
        lines += ["## Notes", ""]
        for label, items in (
            ("Assumptions", result.assumptions),
            ("TODOs", result.todos),
            ("Open Questions", result.open_questions),
        ):
            if items:
                lines.append(f"**{label}:**")
                lines += [f"- {item}" for item in items]
                lines.append("")

    return "\n".join(lines)


