def _esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def _gauge(label: str, value: int, *, color: str = "#8b5cf6") -> str:
    angle = round(value / 100 * 360)
    return f"""
    <div class="gauge">
      <div class="gauge-ring" style="background: conic-gradient({color} {angle}deg, #2a2a35 0deg);">
        <div class="gauge-inner"><span class="gauge-value" data-count="{value}">{value}</span></div>
      </div>
      <div class="gauge-label">{_esc(label)}</div>
    </div>"""


def _bar(label: str, value: int, *, color: str = "#8b5cf6") -> str:
    return f"""
    <div class="bar-row">
      <span class="bar-label">{_esc(label)}</span>
      <div class="bar-track"><div class="bar-fill" style="width:{value}%; background:{color};"></div></div>
      <span class="bar-value">{value}</span>
    </div>"""


