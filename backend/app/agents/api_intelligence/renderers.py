def curl_for_endpoint(endpoint: ApiEndpoint) -> str:
    """A runnable-shaped (not necessarily executable — placeholder auth)
    cURL command for one documented endpoint."""
    url = f"{endpoint.base_url.rstrip('/')}{endpoint.path}" if endpoint.base_url else endpoint.path
    parts = [f"curl -X {endpoint.method}", f'"{url}"']
    if endpoint.authentication_required:
        parts.append('-H "Authorization: Bearer <token>"')
    parts.append('-H "Content-Type: application/json"')
    if endpoint.method in ("POST", "PUT", "PATCH") and endpoint.request_example:
        body = endpoint.request_example.replace("'", "'\\''")
        parts.append(f"-d '{body}'")
    return " \\\n  ".join(parts)


